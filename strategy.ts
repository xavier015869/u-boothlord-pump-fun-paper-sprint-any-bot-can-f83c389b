// Dawn Sniper: a launch sniper for agent-fun/replay/v2 (pump.fun bonding curves).
//
// Idea, from the shape of this market: almost every new coin dies, a few run
// 10-100x. The money is in the tail, so the bot buys launches at birth in small
// size, cuts losers fast, and lets winners run instead of capping them early.
// Entries are filtered for rugs (creator skin in the game, no multi-wallet
// bundle, no creator dump); exits are asymmetric (small stop, large take-profit
// with a trailing stop) so one runner pays for many small losses. Adds only go
// into positions already up, never into losers.
//
// Deterministic by construction: no clock, no randomness, no I/O; iteration only
// over insertion-ordered maps fed by the batch stream.

import type { Batch, BotState, OrderInput, Pubkey } from './vendor/makefun-bot.ts';

export interface Params {
  /** Youngest age (slots since create) at which a coin may be bought. */
  minAge: number;
  /** Oldest age at which a first buy may still be decided. */
  maxAge: number;
  /** Lamports aimed at per coin on the first buy (the 1%-of-reserve cap binds first). */
  stakeLamports: number;
  /** Smallest single buy worth paying the tx fee for. */
  minBuyLamports: number;
  /** Lamports per add-on buy into a winner. */
  addLamports: number;
  /** Most add-on buys per coin. */
  maxAdds: number;
  /** Total lamports aimed at per coin (first buy + adds). */
  maxPerCoinLamports: number;
  /** An add needs the position worth at least this share over its cost (bps). */
  addMinGainBps: number;
  /** An add needs the price at least this far above the last buy's price (bps). */
  addStepBps: number;
  /** Real SOL reserve window at decision time (lamports). */
  minRealSol: number;
  maxRealSol: number;
  /** Creator's own buys in the create slot: lamports window. */
  minDevBuy: number;
  maxDevBuy: number;
  /** Distinct (non-creator) buyers seen before entry, at least: a launch nobody else touched is the creator alone. */
  minBuyers: number;
  /** Distinct (non-creator) buyers seen before entry, at most. */
  maxBuyers: number;
  /** Lamports bought by others before entry, at least. */
  minBoughtLamports: number;
  /** Lamports sold by others / lamports bought, as bps, at most. */
  maxSellRatioBps: number;
  /** The recent-flow window (slots) and what it must show. */
  flowWindow: number;
  minFlowLamports: number;
  /** Slippage allowed on buys (bps). */
  buySlippageBps: number;
  /** First take-profit: sell this share of the position once it is worth this much over cost (bps). */
  tp1Bps: number;
  tp1PartBps: number;
  /** After the first take-profit, sell the rest if it falls back to this much over cost (bps). */
  slAfterTp1Bps: number;
  /** Exit when the position is worth this much over its cost (bps). */
  tpBps: number;
  /** Exit when it is worth this much under its cost (bps). */
  slBps: number;
  /** Trailing stop: once up at least this much, exit on a fall of this much from the best value (bps). */
  trailArmBps: number;
  trailBps: number;
  /** Exit after holding this many slots. */
  maxHold: number;
  /** Exit when the creator sells while held. */
  exitOnDevSell: boolean;
  /** Exit when no trade has hit the coin for this many slots. */
  staleSlots: number;
  /** Fill pacing: prorated fill target over this many seconds of block time. */
  fillTarget: number;
  windowSeconds: number;
  baseSplit: number;
  maxSplit: number;
  /** Smallest buy piece worth sending (lamports). */
  minPieceLamports: number;
}

